// ════════════════════════════════════════════════════════════════════════════
//  CLIENT  — runs in the browser. Self-contained; reads window.__RNS_DATA.
//  Stringified into the page, so it must not reference build-time variables.
// ════════════════════════════════════════════════════════════════════════════
function clientMain() {
  var ALL = "__all";
  function esc(s) { return String(s == null ? "" : s).replace(/[&<>"']/g, function (c) { return ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]; }); }
  function parseVersion(v) { return String(v).split(".").map(Number).reduce(function (a, n) { return a * 1000 + (n || 0); }, 0); }
  function styleFor(facet, val) { return (facet.styles && facet.styles[val]) || null; }
  function labelFor(facet, val) { var s = styleFor(facet, val); return s ? s.label : val; }

  // Distinct values present for a facet, ordered by the configured style order then extras.
  function facetValues(payload, facet) {
    var present = new Set();
    payload.entries.forEach(function (e) {
      if (facet.type === "multi") (e[facet.field] || []).forEach(function (v) { if (v) present.add(v); });
      else if (e[facet.field]) present.add(e[facet.field]);
    });
    var ordered = Object.keys(facet.styles || {}).filter(function (k) { return present.has(k); });
    var extras = [...present].filter(function (k) { return ordered.indexOf(k) === -1; }).sort();
    return ordered.concat(extras);
  }

  function chip(facet, val) {
    var s = styleFor(facet, val);
    var bg = s ? s.bg : "#F3F4F6", color = s ? s.color : "#374151";
    return '<span class="chip" style="background:' + bg + ';color:' + color + '">' + esc(labelFor(facet, val)) + "</span>";
  }

  function renderPane(root, payload) {
    var facetsWithValues = payload.facets
      .map(function (f) { return { facet: f, values: facetValues(payload, f) }; })
      .filter(function (fv) { return fv.values.length > 0; });

    // ── header sub + stats ──
    var versionsSorted = payload.versions.slice().sort(function (a, b) { return parseVersion(b.version) - parseVersion(a.version); });
    var newestV = versionsSorted.length ? versionsSorted[0].version : "";
    var oldestV = versionsSorted.length ? versionsSorted[versionsSorted.length - 1].version : "";
    var dated = payload.entries.filter(function (e) { return e.date; }).map(function (e) { return e.dateDisplay; });
    var subBits = [];
    if (oldestV) subBits.push("Versions " + oldestV + " – " + newestV);
    subBits.push(payload.versions.length + " releases");
    if (payload.generated) subBits.push("updated " + payload.generated);

    var needsReview = payload.entries.filter(function (e) { return e.status === "needs-review"; }).length;
    var primaryCount = 0;
    if (payload.primaryStat) {
      var pf = payload.facets.filter(function (f) { return f.key === payload.primaryStat.facet; })[0];
      if (pf) primaryCount = facetValues(payload, pf).length;
    }

    var statsHtml =
      stat(payload.itemNoun, payload.entries.length) +
      stat("Releases", payload.versions.length) +
      (payload.primaryStat ? stat(payload.primaryStat.label, primaryCount) : "") +
      stat("Needs review", needsReview, needsReview > 0 ? "stat-review" : "");
    function stat(lbl, val, cls) { return '<div class="stat ' + (cls || "") + '"><span class="stat-val">' + val + '</span><span class="stat-lbl">' + esc(lbl) + "</span></div>"; }

    // ── facet filter groups ──
    var facetGroupsHtml = facetsWithValues.map(function (fv) {
      var pills = fv.values.map(function (v) {
        return '<button class="pill ' + (fv.facet.accent ? "accent-pill" : "") + '" data-fval="' + esc(v) + '">' + esc(labelFor(fv.facet, v)) + "</button>";
      }).join("");
      return '<div class="filter-group" data-facet="' + esc(fv.facet.key) + '"><span class="filter-label">' + esc(fv.facet.label) + '</span>' +
        '<button class="pill ' + (fv.facet.accent ? "accent-pill" : "") + ' active" data-fval="' + ALL + '">All</button>' + pills + "</div>";
    }).join("");

    // ── table head ──
    var headCols = ['<th class="sortable" data-sort="version">Version <span class="sort-arrow">↕</span></th>',
      '<th class="sortable" data-sort="date">Release date <span class="sort-arrow">↕</span></th>'];
    facetsWithValues.forEach(function (fv) {
      var sortable = fv.facet.type === "single";
      headCols.push("<th" + (sortable ? ' class="sortable" data-sort="facet:' + esc(fv.facet.field) + '"' : "") + ">" + esc(fv.facet.label) + (sortable ? ' <span class="sort-arrow">↕</span>' : "") + "</th>");
    });
    headCols.push("<th>Description</th>");
    headCols.push("<th>Release notes</th>");

    root.innerHTML =
      '<header class="page-header"><div class="header-eyebrow">' + esc(payload.eyebrow || "Release notes overview") + "</div>" +
      '<h1 class="header-title">' + esc(payload.productName) + " — New Features</h1>" +
      '<p class="header-sub">' + esc(subBits.join("  ·  ")) + "</p>" +
      '<div class="header-stats">' + statsHtml + "</div></header>" +
      '<div class="controls"><div class="search-wrap">' +
      '<svg width="14" height="14" fill="none" viewBox="0 0 24 24" stroke="currentColor" stroke-width="2"><circle cx="11" cy="11" r="8"/><path d="m21 21-4.35-4.35"/></svg>' +
      '<input class="search-input" type="search" data-el="search" placeholder="Search…"></div>' +
      facetGroupsHtml +
      '<span class="result-count" data-el="count"></span></div>' +
      versionFilterSkeleton() +
      '<div class="table-wrap"><div class="review-banner" data-el="review"></div>' +
      '<table><thead><tr>' + headCols.join("") + "</tr></thead><tbody data-el=\"tbody\"></tbody></table>" +
      '<div class="no-results" data-el="noresults">No items match your filters.</div></div>' +
      '<footer class="page-footer">Source: <a href="' + esc(payload.source) + '" target="_blank" rel="noopener">' + esc(payload.productName) + " release notes</a></footer>";

    if (needsReview > 0) {
      var rb = root.querySelector('[data-el="review"]');
      rb.textContent = "⚠ " + needsReview + " entr" + (needsReview === 1 ? "y is" : "ies are") + " auto-extracted and awaiting review — tags may be incomplete.";
      rb.classList.add("visible");
    }

    wirePane(root, payload, facetsWithValues, versionsSorted);
  }

  function versionFilterSkeleton() {
    return '<div class="controls-version" data-el="versionrow">' +
      '<div class="controls-version-header" data-el="vtoggle"><span class="filter-label" style="margin:0">Version filter</span>' +
      '<span class="version-active-hint" data-el="vhint"></span>' +
      '<svg class="version-chevron" width="14" height="14" fill="none" viewBox="0 0 24 24" stroke="currentColor" stroke-width="2"><polyline points="6 9 12 15 18 9"/></svg></div>' +
      '<div class="controls-version-body"><div style="width:100%">' +
      '<div class="vf-tabs"><button class="vf-tab active" data-vtab="select">Select versions</button><button class="vf-tab" data-vtab="upgrade">Upgrade path</button></div>' +
      '<div class="vf-panel active" data-vpanel="select"><div class="mode-toggle">' +
      '<button class="mode-btn active" data-mode="include">Include</button><button class="mode-btn" data-mode="exclude">Exclude</button></div>' +
      '<div class="version-pills" data-el="vpills"></div></div>' +
      '<div class="vf-panel" data-vpanel="upgrade"><div class="upgrade-selects">' +
      '<span style="font-size:12px;color:var(--muted);white-space:nowrap">Upgrading from</span>' +
      '<select class="upgrade-select" data-el="ufrom"><option value="">— select version —</option></select>' +
      '<span class="upgrade-arrow">→</span><span style="font-size:12px;color:var(--muted);white-space:nowrap">to</span>' +
      '<select class="upgrade-select" data-el="uto"><option value="">— select version —</option></select></div>' +
      '<span class="upgrade-summary" data-el="usummary"></span><button class="upgrade-clear" data-el="uclear">Clear</button></div>' +
      "</div></div></div>";
  }

  function wirePane(root, payload, facetsWithValues, versionsSorted) {
    var q = function (sel) { return root.querySelector(sel); };
    var qa = function (sel) { return Array.prototype.slice.call(root.querySelectorAll(sel)); };

    var state = {
      search: "", facetSel: {}, versions: new Set(), versionMode: "include",
      versionTab: "select", upgradeFrom: "", upgradeTo: "", sortKey: "date", sortAsc: false,
    };
    facetsWithValues.forEach(function (fv) { state.facetSel[fv.facet.key] = fv.facet.type === "multi" ? new Set([ALL]) : ALL; });

    // Build rows
    var tbody = q('[data-el="tbody"]');
    payload.entries.forEach(function (e, i) {
      var tr = document.createElement("tr");
      tr.dataset.index = i;
      var cells = ['<td class="td-version">' + esc(e.version) + "</td>",
        '<td class="td-date">' + esc(e.dateDisplay || "") + "</td>"];
      facetsWithValues.forEach(function (fv) {
        if (fv.facet.type === "multi") {
          var vals = e[fv.facet.field] || [];
          cells.push('<td><div class="chips">' + vals.map(function (v) { return chip(fv.facet, v); }).join(" ") + "</div></td>");
        } else {
          var v = e[fv.facet.field];
          cells.push("<td>" + (v ? chip(fv.facet, v) : '<span class="td-muted">—</span>') + "</td>");
        }
      });
      var reviewBadge = e.status === "needs-review" ? '<span class="review-badge">Review</span>' : "";
      cells.push('<td class="td-feature">' + esc(e.text) + reviewBadge + "</td>");
      cells.push('<td class="td-link"><a href="' + esc(e.link) + '" target="_blank" rel="noopener">' + esc(e.version) +
        '<svg width="11" height="11" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M18 13v6a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2V8a2 2 0 0 1 2-2h6"/><polyline points="15 3 21 3 21 9"/><line x1="10" y1="14" x2="21" y2="3"/></svg></a></td>');
      tr.innerHTML = cells.join("");
      tbody.appendChild(tr);
    });

    // Version pills + upgrade dropdowns
    var vpills = q('[data-el="vpills"]');
    vpills.innerHTML = versionsSorted.map(function (v) { return '<button class="pill" data-version="' + esc(v.version) + '">' + esc(v.version) + "</button>"; }).join("");
    var opts = '<option value="">— select version —</option>' + versionsSorted.map(function (v) { return '<option value="' + esc(v.version) + '">' + esc(v.version) + "</option>"; }).join("");
    q('[data-el="ufrom"]').innerHTML = opts;
    q('[data-el="uto"]').innerHTML = opts;
    if (versionsSorted.length) { q('[data-el="uto"]').value = versionsSorted[0].version; state.upgradeTo = versionsSorted[0].version; }

    // ── filtering ──
    function entryMatchesFacets(e) {
      return facetsWithValues.every(function (fv) {
        var sel = state.facetSel[fv.facet.key];
        if (fv.facet.type === "multi") {
          if (sel.has(ALL) || sel.size === 0) return true;
          return (e[fv.facet.field] || []).some(function (v) { return sel.has(v); });
        }
        if (sel === ALL) return true;
        return (e[fv.facet.field] || "") === sel;
      });
    }
    function applyFilters() {
      var rows = qa('[data-el="tbody"] tr');
      var visible = 0;
      rows.forEach(function (tr) {
        var e = payload.entries[+tr.dataset.index];
        var matchText = !state.search ||
          (e.text + " " + e.version + " " + (e.dateDisplay || "")).toLowerCase().indexOf(state.search) !== -1;
        var matchFacets = entryMatchesFacets(e);
        var matchVersion = true;
        if (state.versionTab === "upgrade" && state.upgradeFrom && state.upgradeTo) {
          var rv = parseVersion(e.version), lo = Math.min(parseVersion(state.upgradeFrom), parseVersion(state.upgradeTo)), hi = Math.max(parseVersion(state.upgradeFrom), parseVersion(state.upgradeTo));
          matchVersion = rv > lo && rv <= hi;
        } else if (state.versionTab === "select" && state.versions.size > 0) {
          var inSet = state.versions.has(e.version);
          matchVersion = state.versionMode === "include" ? inSet : !inSet;
        }
        if (matchText && matchFacets && matchVersion) { tr.classList.remove("hidden"); visible++; }
        else tr.classList.add("hidden");
      });
      q('[data-el="count"]').textContent = visible + " " + (visible === 1 ? "result" : "results");
      q('[data-el="noresults"]').style.display = visible === 0 ? "block" : "none";
    }

    // ── sorting ──
    function sortBy(key) {
      if (state.sortKey === key) state.sortAsc = !state.sortAsc;
      else { state.sortKey = key; state.sortAsc = key.indexOf("facet:") === 0; }
      qa("th").forEach(function (th) { th.classList.remove("sorted"); });
      var th = q('th[data-sort="' + key + '"]'); if (th) th.classList.add("sorted");
      var rows = qa('[data-el="tbody"] tr');
      rows.sort(function (a, b) {
        var ea = payload.entries[+a.dataset.index], eb = payload.entries[+b.dataset.index], va, vb;
        if (key === "version") { va = parseVersion(ea.version); vb = parseVersion(eb.version); }
        else if (key === "date") { va = ea.date || ""; vb = eb.date || ""; }
        else { var f = key.slice(6); va = ea[f] || ""; vb = eb[f] || ""; }
        if (typeof va === "number") return state.sortAsc ? va - vb : vb - va;
        return state.sortAsc ? String(va).localeCompare(vb) : String(vb).localeCompare(va);
      });
      rows.forEach(function (r) { tbody.appendChild(r); });
      applyFilters();
    }

    function updateHint() {
      var hint = q('[data-el="vhint"]');
      if (state.versionTab === "upgrade" && state.upgradeFrom && state.upgradeTo) { hint.textContent = state.upgradeFrom + " → " + state.upgradeTo; hint.classList.add("visible"); }
      else if (state.versionTab === "select" && state.versions.size > 0) { hint.textContent = (state.versionMode === "exclude" ? "excluding " : "including ") + state.versions.size + " version" + (state.versions.size !== 1 ? "s" : ""); hint.classList.add("visible"); }
      else { hint.textContent = ""; hint.classList.remove("visible"); }
    }

    // ── wire events ──
    q('[data-el="search"]').addEventListener("input", function (ev) { state.search = ev.target.value.toLowerCase(); applyFilters(); });

    qa(".filter-group").forEach(function (group) {
      var key = group.dataset.facet;
      var facet = facetsWithValues.filter(function (fv) { return fv.facet.key === key; })[0].facet;
      group.addEventListener("click", function (ev) {
        var btn = ev.target.closest(".pill"); if (!btn) return;
        var val = btn.dataset.fval;
        if (facet.type === "multi") {
          var sel = state.facetSel[key];
          if (val === ALL) sel = new Set([ALL]);
          else { sel.delete(ALL); if (sel.has(val)) { sel.delete(val); if (sel.size === 0) sel.add(ALL); } else sel.add(val); }
          state.facetSel[key] = sel;
          qa('[data-facet="' + key + '"] .pill').forEach(function (b) { b.classList.toggle("active", sel.has(b.dataset.fval)); });
        } else {
          state.facetSel[key] = val;
          qa('[data-facet="' + key + '"] .pill').forEach(function (b) { b.classList.toggle("active", b.dataset.fval === val); });
        }
        applyFilters();
      });
    });

    qa("th.sortable").forEach(function (th) { th.addEventListener("click", function () { sortBy(th.dataset.sort); }); });

    q('[data-el="vtoggle"]').addEventListener("click", function () { q('[data-el="versionrow"]').classList.toggle("open"); });
    qa('[data-mode]').forEach(function (b) { b.addEventListener("click", function () { state.versionMode = b.dataset.mode; qa('[data-mode]').forEach(function (x) { x.classList.toggle("active", x.dataset.mode === state.versionMode); }); updateHint(); applyFilters(); }); });
    qa('[data-vtab]').forEach(function (b) { b.addEventListener("click", function () { state.versionTab = b.dataset.vtab; qa('[data-vtab]').forEach(function (x) { x.classList.toggle("active", x.dataset.vtab === state.versionTab); }); qa('[data-vpanel]').forEach(function (p) { p.classList.toggle("active", p.dataset.vpanel === state.versionTab); }); updateHint(); applyFilters(); }); });
    vpills.addEventListener("click", function (ev) {
      var btn = ev.target.closest(".pill"); if (!btn) return;
      var v = btn.dataset.version;
      if (state.versions.has(v)) state.versions.delete(v); else state.versions.add(v);
      btn.classList.toggle("active", state.versions.has(v)); updateHint(); applyFilters();
    });
    function applyUpgrade() {
      state.upgradeFrom = q('[data-el="ufrom"]').value; state.upgradeTo = q('[data-el="uto"]').value;
      var active = state.upgradeFrom && state.upgradeTo;
      var summary = q('[data-el="usummary"]'), clr = q('[data-el="uclear"]');
      if (active) {
        var lo = parseVersion(state.upgradeFrom) < parseVersion(state.upgradeTo) ? state.upgradeFrom : state.upgradeTo;
        var hi = lo === state.upgradeFrom ? state.upgradeTo : state.upgradeFrom;
        summary.textContent = "New features after " + lo + " up to and including " + hi; summary.classList.add("visible"); clr.classList.add("visible");
      } else { summary.classList.remove("visible"); clr.classList.remove("visible"); }
      updateHint(); applyFilters();
    }
    q('[data-el="ufrom"]').addEventListener("change", applyUpgrade);
    q('[data-el="uto"]').addEventListener("change", applyUpgrade);
    q('[data-el="uclear"]').addEventListener("click", function () { state.upgradeFrom = ""; state.upgradeTo = ""; q('[data-el="ufrom"]').value = ""; q('[data-el="uto"]').value = ""; applyUpgrade(); });

    // initial sort (date desc) + render
    sortBy("date");
  }

  // ── boot ──
  var data = window.__RNS_DATA || [];
  data.forEach(function (payload) {
    var root = document.querySelector('.product-pane[data-product="' + payload.product + '"]');
    if (root) renderPane(root, payload);
  });
  // product tabs
  var tabs = Array.prototype.slice.call(document.querySelectorAll(".ptab"));
  tabs.forEach(function (tab) {
    tab.addEventListener("click", function () {
      tabs.forEach(function (t) { t.classList.remove("active"); });
      tab.classList.add("active");
      Array.prototype.slice.call(document.querySelectorAll(".product-pane")).forEach(function (p) {
        p.classList.toggle("active", p.dataset.product === tab.dataset.ptab);
      });
    });
  });
}

main();
