"use strict";

/**
 * Build the self-contained HTML overviews from data/<product>.json:
 *
 *   site/monitor.html                (Redgate Monitor)
 *   site/flyway.html                 (Redgate Flyway)
 *   site/test-data-manager.html      (Redgate Test Data Manager)
 *   site/all-products.html           (all three, as tabs)
 *   site/index.html                  (redirect to all-products.html, for GitHub Pages)
 *
 * Each per-product page is fully standalone (data inlined, no network needed) so it
 * can be emailed/shared and opened with a double-click. The combined page embeds all
 * three datasets and switches between them with tabs.
 */

const fs = require("fs");
const path = require("path");
const { PRODUCTS } = require("./lib/products");

const ROOT = path.join(__dirname, "..");
const DATA_DIR = path.join(ROOT, "data");
const SITE_DIR = path.join(ROOT, "site");

// ── Build a payload (config + data) for the client renderer ──
function buildPayload(productKey) {
  const product = PRODUCTS[productKey];
  const file = path.join(DATA_DIR, `${productKey}.json`);
  if (!fs.existsSync(file)) return null;
  const data = JSON.parse(fs.readFileSync(file, "utf8"));
  return {
    product: product.key,
    productName: product.name,
    eyebrow: product.eyebrow,
    source: data.source || product.source,
    generated: data.generated || "",
    itemNoun: product.key === "monitor" ? "Features" : "Entries",
    primaryStat: product.primaryStat || null,
    facets: product.facets.map((f) => ({
      key: f.key,
      label: f.label,
      field: f.field,
      type: f.type,
      accent: !!f.accent,
      styles: f.styles || {},
    })),
    versions: data.versions || [],
    entries: data.entries || [],
  };
}

// ── HTML document scaffold ──
function htmlDoc(title, bodyInner, payloads) {
  const json = JSON.stringify(payloads).replace(/</g, "\\u003c");
  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${escapeHtml(title)}</title>
<style>
${CSS}
</style>
</head>
<body>
${bodyInner}
<footer class="page-footer">Redgate release-notes overview · generated by the RG-RNS pipeline</footer>
<script>
window.__RNS_DATA = ${json};
(${clientMain.toString()})();
</script>
</body>
</html>
`;
}

function paneSkeleton(key, active) {
  return `<section class="product-pane${active ? " active" : ""}" data-product="${key}"></section>`;
}

function escapeHtml(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
}

// ── Main ──
function main() {
  fs.mkdirSync(SITE_DIR, { recursive: true });
  const keys = Object.keys(PRODUCTS).filter((k) => fs.existsSync(path.join(DATA_DIR, `${k}.json`)));

  // Per-product standalone pages
  for (const key of keys) {
    const payload = buildPayload(key);
    const html = htmlDoc(`${payload.productName} — New Features`, paneSkeleton(key, true), [payload]);
    const out = path.join(SITE_DIR, PRODUCTS[key].outFile);
    fs.writeFileSync(out, html, "utf8");
    console.log(`[build] ${path.relative(ROOT, out)} (${payload.entries.length} entries)`);
  }

  // Combined tabbed page
  const payloads = keys.map(buildPayload);
  const tabs =
    `<div class="product-tabs">` +
    keys
      .map((k, i) => `<button class="ptab${i === 0 ? " active" : ""}" data-ptab="${k}">${escapeHtml(PRODUCTS[k].name)}</button>`)
      .join("") +
    `</div>`;
  const panes = keys.map((k, i) => paneSkeleton(k, i === 0)).join("\n");
  const combined = htmlDoc("Redgate Products — Release Notes Overview", tabs + "\n" + panes, payloads);
  fs.writeFileSync(path.join(SITE_DIR, "all-products.html"), combined, "utf8");
  console.log(`[build] site/all-products.html (${keys.length} products)`);

  // Pages landing redirect (not a product page — just routing)
  const redirect = `<!DOCTYPE html><html lang="en"><head><meta charset="UTF-8">
<title>Redgate Release Notes</title>
<meta http-equiv="refresh" content="0; url=all-products.html">
<link rel="canonical" href="all-products.html"></head>
<body><p>Redirecting to <a href="all-products.html">the release-notes overview</a>…</p></body></html>
`;
  fs.writeFileSync(path.join(SITE_DIR, "index.html"), redirect, "utf8");
  console.log(`[build] site/index.html (redirect → all-products.html)`);
}

